import { readFileSync } from "node:fs";

export const UI_FILES = ["index.html", "app.js", "style.css"] as const;

/** Source of src/ui-assets.generated.ts. Node only (reads public/); never imported by the Worker path. */
export function uiAssetsModule(): string {
  // LF everywhere, so a Windows checkout (autocrlf) generates the same file as Linux CI.
  const read = (name: string) => readFileSync(new URL(`../public/${name}`, import.meta.url), "utf8").replace(/\r\n/g, "\n");
  const entries = UI_FILES.map(name => `  ${JSON.stringify(name)}: ${JSON.stringify(read(name))},`);
  return `// Generated by scripts/ui-assets.ts from public/. Do not edit; a test fails if it is stale.
// Embedded so the Labyrinth page also works on Cloudflare Workers, which have no filesystem.
export const UI_ASSETS: Record<"index.html" | "app.js" | "style.css", string> = {
${entries.join("\n")}
};
`;
}
