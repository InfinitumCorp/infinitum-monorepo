"""
The :\\ARCHITECT\\ logo mark, ":\\™", in Arial Regular (ink #111820 on white), for every icon:
the web app (icon.svg, PNGs via scripts/icons.mjs), the Chrome extension and the Android launcher.

    python scripts/logo.py [path/to/arial.ttf]      (needs fonttools: python -m pip install fonttools)

Glyph outlines are written as paths, so no font is needed at run time.
"""
import os
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.environ.get("WINDIR", "C:/Windows"), "Fonts", "arial.ttf")
INK, PAPER = "#111820", "#FFFFFF"
GRID = 108          # Android adaptive-icon grid; the web icons use the same coordinates
SAFE = 60           # the mark's width stays inside the adaptive-icon safe zone (66) with a margin
CENTER_Y = 54

font = TTFont(FONT)
glyphs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
UPM = font["head"].unitsPerEm


def bounds(name):
    from fontTools.pens.boundsPen import BoundsPen
    p = BoundsPen(glyphs)
    glyphs[name].draw(p)
    return p.bounds


def mark(height=38, tm=0.46, gap=0.05):
    """
    ":\\" at `height` grid units tall, with "™" at `tm` of that size as a superscript whose top
    lines up with the top of the backslash. The whole mark is centred in the grid. Returns SVG path data.
    """
    colon, back, mark_tm = cmap[ord(":")], cmap[ord("\\")], cmap[0x2122]
    bb = bounds(back)
    s = height / (bb[3] - bb[1])  # font units -> grid units
    t = s * tm
    # Pen x positions (font units at scale s) for colon and backslash; ™ follows after a small gap.
    xs = [(colon, 0, s), (back, hmtx[colon][0], s)]
    # The backslash leans right, so its top is near its left edge: tuck the ™ in from the middle of its width.
    right = (hmtx[colon][0] + (bb[0] + bb[2]) / 2) * s + gap * height
    tb = bounds(mark_tm)
    tm_x = right - tb[0] * t
    left = bounds(colon)[0] * s
    width = tm_x + tb[2] * t - left
    ox = (GRID - width) / 2 - left
    top = CENTER_Y - height / 2           # grid y of the backslash top
    base = top + bb[3] * s                 # baseline for colon and backslash
    tm_base = top + tb[3] * t              # baseline that puts the ™ top on the backslash top
    out = []
    for name, px, k in xs:
        out.append(draw(name, ox + px * s, base, k))
    out.append(draw(mark_tm, ox + tm_x, tm_base, t))
    return " ".join(out)


def draw(name, x, baseline, k):
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    glyphs[name].draw(TransformPen(pen, (k, 0, 0, -k, x, baseline)))
    return pen.getCommands()


def write(rel, text):
    path = os.path.join(ROOT, rel)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", rel)


d = mark()
note = "Generated by scripts/logo.py: the :\\ARCHITECT\\ mark :\\™ in Arial Regular, ink #111820 on white."
write("web/icon.svg",
      f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72"><title>:\\ARCHITECT\\™</title>'
      f'<rect x="0" y="0" width="{GRID}" height="{GRID}" fill="{PAPER}"/><path d="{d}" fill="{INK}"/></svg>\n')
vec = lambda w, body: (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {note} -->\n'
                       f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                       f'    android:width="{w}dp" android:height="{w}dp"\n'
                       f'    android:viewportWidth="{GRID}" android:viewportHeight="{GRID}">\n{body}</vector>\n')
write("android/res/drawable/ic_launcher_mark.xml", vec(108, f'    <path android:fillColor="{INK}" android:pathData="{d}" />\n'))
write("android/res/drawable/ic_launcher.xml", vec(48,
      f'    <path android:fillColor="{PAPER}" android:pathData="M24,18h60a6,6 0 0 1 6,6v60a6,6 0 0 1 -6,6h-60a6,6 0 0 1 -6,-6v-60a6,6 0 0 1 6,-6z" />\n'
      f'    <path android:fillColor="{INK}" android:pathData="{d}" />\n'))
